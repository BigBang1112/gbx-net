using GBX.NET.Generators.Analysis;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace GBX.NET.Generators.Generation;

internal static class GameApiWriter
{
    private static readonly DiagnosticDescriptor InvalidApi = new("GBXNETGEN300", "Cannot generate game API",
        "Cannot generate game API for {0}: {1}", "GBX.NET.Generators", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor MissingRecipe = new("GBXNETGEN301", "Game creation recipe is incomplete",
        "No {1} builder for {0}: {2}", "GBX.NET.Generators", DiagnosticSeverity.Info, true);
    private static readonly DiagnosticDescriptor MissingMember = new("GBXNETGEN302", "Game member context is incomplete",
        "Cannot project {0}: {1}", "GBX.NET.Generators", DiagnosticSeverity.Info, true);

    public static void Generate(SourceProductionContext context, GenerationPlan plan, Compilation compilation)
    {
        // Lightweight serializer fixtures and downstream consumers need not provide
        // the library's builder runtime. Do not emit an API they cannot support.
        if (compilation.GetTypeByMetadataName("GBX.NET.Builders.NodeBuilderState`1") is null ||
            compilation.GetTypeByMetadataName("GBX.NET.IClassVersion`1") is null ||
            compilation.GetTypeByMetadataName("GBX.NET.GameVersion") is null) return;

        Dictionary<string, GameNodeModel> nodes;
        try
        {
            nodes = GameNodeModel.Create(plan, compilation);
        }
        catch (Exception exception) when (exception is not OperationCanceledException)
        {
            context.ReportDiagnostic(Diagnostic.Create(InvalidApi, Location.None, "game metadata", exception.Message));
            return;
        }
        var coverage = new List<string>();
        foreach (var node in nodes.Values.OrderBy(static n => n.Layout.File.TypeKey, StringComparer.Ordinal))
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            if (node.MetadataError is not null)
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidApi, Location.Create(node.Layout.File.Path, default, default),
                    node.Layout.Name, node.MetadataError));
                continue;
            }
            if (node.Games.Count == 0)
            {
                coverage.Add(node.Layout.Name + ": no game writer metadata");
                continue;
            }
            try
            {
                foreach (var error in node.MemberErrors)
                {
                    coverage.Add(node.Layout.Name + "/" + error);
                    context.ReportDiagnostic(Diagnostic.Create(MissingMember, Location.Create(node.Layout.File.Path, default, default),
                        node.Layout.Name, error));
                }
                foreach (var game in node.RecipeErrors)
                {
                    coverage.Add(node.Layout.Name + "/" + game.Key + ": " + game.Value);
                    context.ReportDiagnostic(Diagnostic.Create(MissingRecipe, Location.Create(node.Layout.File.Path, default, default),
                        node.Layout.Name, game.Key, game.Value));
                }
                context.AddSource($"Interfaces/{node.Layout.File.Engine}/{node.InterfaceName}.g.cs", Interfaces(node, plan, nodes, compilation));
                context.AddSource($"GameApis/{node.Layout.File.Engine}/{node.Layout.Name}.g.cs", Node(node, plan, nodes));
                if (!node.Layout.IsAbstract && node.Games.Any(g => !node.RecipeErrors.ContainsKey(g)))
                    context.AddSource($"Builders/{node.Layout.File.Engine}/{node.BuilderName}.g.cs", Builder(node, plan, nodes));
            }
            catch (Exception exception) when (exception is not OperationCanceledException)
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidApi, Location.Create(node.Layout.File.Path, default, default),
                    node.Layout.Name, exception.Message));
            }
        }
        var report = new CodeWriter();
        report.Line("// <auto-generated />");
        report.Line("namespace GBX.NET.Builders;");
        report.Open("internal static class NodeBuilderCoverage");
        report.Line("internal const string IncompleteRecipes = " + SymbolDisplay.FormatLiteral(string.Join("\n", coverage), true) + ";");
        report.Close();
        context.AddSource("Builders/NodeBuilderCoverage.g.cs", report.ToString());
    }

    private static CodeWriter Start(string ns, GenerationPlan plan)
    {
        var code = new CodeWriter();
        code.Line("// <auto-generated />");
        code.Line("#nullable enable");
        foreach (var import in new[] { "System", "System.Collections.Generic", "System.Linq", "System.Collections.Immutable",
            "TmEssentials", "GBX.NET", "GBX.NET.Builders", "GBX.NET.Exceptions", "GBX.NET.Serialization.Chunking" }
            .Concat(plan.Layouts.Values.Select(static l => l.File.Namespace)).Distinct().OrderBy(static x => x, StringComparer.Ordinal))
            code.Line("using global::" + import + ";");
        code.BlankLine();
        code.Line("namespace " + ns + ";");
        code.BlankLine();
        return code;
    }

    private static string Interfaces(GameNodeModel node, GenerationPlan plan, Dictionary<string, GameNodeModel> nodes, Compilation compilation)
    {
        var code = Start(node.InterfaceNamespace, plan);
        var parent = node.Layout.BaseName is not null && nodes.TryGetValue(node.Layout.BaseName, out var ancestor) &&
            ancestor.Games.Count > 0 ? ancestor : null;
        foreach (var game in new[] { "" }.Concat(node.Games))
        {
            var name = node.InterfaceName + game;
            if (plan.Existing.TryGetValue(node.InterfaceNamespace + "." + name, out var existing) && !existing.IsPartial)
                throw new InvalidOperationException("Existing interface must be partial: " + existing.Key);
            var bases = new List<string> { game.Length == 0 ? $"IClassVersion<{node.Layout.QualifiedName}>" : node.InterfaceName };
            if (parent is not null && (game.Length == 0 || parent.Games.Contains(game))) bases.Add(parent.Interface(game));
            code.Open($"public partial interface {name} : " + string.Join(", ", bases));
            if (game.Length == 0 && parent is not null)
                CommonClassContract(code, compilation.GetTypeByMetadataName("GBX.NET.IClassVersion`1")!);
            var members = game.Length == 0 ? node.Common : node.Members.Where(m => m.Games.Contains(game));
            foreach (var member in members)
            {
                if (ExistingProperty(plan, node, game, member, nodes)) continue;
                var common = game.Length > 0 && node.Common.Any(m => m.Name == member.Name);
                var type = Project(member, game, nodes);
                if (common && type == Project(member, "", nodes)) continue;
                var hidesInherited = common || GameNodeModel.ExistingContract(plan, node, game, member.Name) is not null ||
                    parent?.Members.Any(m => m.Name == member.Name && (game.Length == 0 ? parent.Games.All(m.Games.Contains) : m.Games.Contains(game))) == true;
                code.Line($"{(hidesInherited ? "new " : "")}{type} {SyntaxOverlap.Escape(member.Name)} {{ get;{(member.Writable ? " set;" : "")} }}");
            }
            foreach (var method in node.Methods.Where(m => game.Length == 0 ? node.Games.All(m.Games.Contains) : m.Games.Contains(game)))
            {
                if (ExistingMethod(plan, node, game, method)) continue;
                var common = game.Length > 0 && node.Games.All(method.Games.Contains);
                var returned = ProjectReturn(method, game, nodes);
                if (common && returned == ProjectReturn(method, "", nodes)) continue;
                code.Line($"{(common ? "new " : "")}{returned} {method.Declaration.Identifier.Text}({method.Parameters});");
            }
            code.Close();
            code.BlankLine();
        }
        return code.ToString();
    }

    private static void CommonClassContract(CodeWriter code, INamedTypeSymbol contract)
    {
        // A derived node retains IClassVersion<Derived> for typed parsing, while
        // its base view carries IClassVersion<Base>. Redeclare their shared
        // operations once on the derived common view to avoid ambiguous calls.
        foreach (var property in contract.GetMembers().OfType<IPropertySymbol>())
            code.Line($"new {property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)} {SyntaxOverlap.Escape(property.Name)} {{ get; }}");
        foreach (var method in contract.GetMembers().OfType<IMethodSymbol>().Where(static m => m.MethodKind == MethodKind.Ordinary))
        {
            var parameters = string.Join(", ", method.Parameters.Select(p => p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) +
                " " + SyntaxOverlap.Escape(p.Name) + (p.HasExplicitDefaultValue ? " = " + DefaultParameter(p.ExplicitDefaultValue) : "")));
            code.Line($"new {method.ReturnType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)} {SyntaxOverlap.Escape(method.Name)}({parameters});");
        }
    }

    private static string DefaultParameter(object? value) => value switch
    {
        null => "default",
        bool boolean => boolean ? "true" : "false",
        string text => SymbolDisplay.FormatLiteral(text, true),
        _ => Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture) ?? "default"
    };

    private static bool ExistingProperty(GenerationPlan plan, GameNodeModel node, string game, GameMember member,
        Dictionary<string, GameNodeModel> nodes)
    {
        return plan.Existing.TryGetValue(node.InterfaceNamespace + "." + node.InterfaceName + game, out var type) &&
            type.Properties.Any(p => p.Identifier.ValueText == member.Name) ||
            game.Length > 0 && GameNodeModel.ExistingContract(plan, node, game, member.Name) is not null &&
            Project(member, game, nodes) == member.Type;
    }

    private static string Project(GameMember member, string game, Dictionary<string, GameNodeModel> nodes)
    {
        var field = member.Field;
        if (field is null || !(member.IsReference || member.Type.Contains("NodeRefList<")) || field.StorageDeclaration.Type.ArrayDimensions > 1 ||
            !nodes.TryGetValue(WireTypes.Map(field.StorageDeclaration.Type.Name), out var child) || child.Games.Count == 0 ||
            game.Length > 0 && !child.Games.Contains(game)) return member.Type;
        if (field.StorageDeclaration.Type.ArrayDimensions == 0)
            return child.Interface(game) + (member.Type.EndsWith("?", StringComparison.Ordinal) ? "?" : "");
        return "IReadOnlyList<" + child.Interface(game) + (field.Occurrences.Any(static o => o.Type.IsNullable) ? "?" : "") + ">" +
            (member.Type.EndsWith("?", StringComparison.Ordinal) ? "?" : "");
    }

    private static string ProjectReturn(GameMethod method, string game, Dictionary<string, GameNodeModel> nodes)
    {
        var type = method.ReturnType;
        foreach (var child in nodes.Values.Where(n => n.Games.Count > 0 && (game.Length == 0 || n.Games.Contains(game))))
        {
            if (type == child.Layout.QualifiedName || type == child.Layout.QualifiedName + "?" ||
                type == "IEnumerable<" + child.Layout.QualifiedName + ">" || type == "IEnumerable<" + child.Layout.QualifiedName + "?>")
                return type.Replace(child.Layout.QualifiedName, child.Interface(game));
        }
        return type;
    }

    private static bool ExistingMethod(GenerationPlan plan, GameNodeModel node, string game, GameMethod method)
        => plan.Existing.TryGetValue(node.InterfaceNamespace + "." + node.InterfaceName + game, out var existing) &&
            SyntaxOverlap.Method(existing, method.Declaration.Identifier.ValueText, method.Declaration.ParameterList.Parameters
                .Select(static p => p.Type?.ToString() ?? "object").ToArray());

    private static string Node(GameNodeModel node, GenerationPlan plan, Dictionary<string, GameNodeModel> nodes)
    {
        var code = Start(node.Layout.File.Namespace, plan);
        code.Open("public partial class " + node.Layout.Name + " : " + string.Join(", ", new[] { "" }.Concat(node.Games).Select(node.Interface)));
        if (!node.Layout.IsAbstract && node.Games.Any(g => !node.RecipeErrors.ContainsKey(g)) &&
            node.Layout.Existing?.Methods.Any(static m => m.Identifier.ValueText == "Create" &&
                m.Modifiers.Any(SyntaxKind.StaticKeyword) && m.TypeParameterList is null && m.ParameterList.Parameters.Count == 0) != true)
        {
            var parentFactory = GameNodeModel.Hierarchy(node.Layout, plan.Layouts).Skip(1)
                .Any(l => nodes[l.Name].Games.Count > 0 && !l.IsAbstract);
            code.Line($"public static {(parentFactory ? "new " : "")}global::{node.BuilderNamespace}.{node.BuilderName} Create() => new();");
        }

        if (node.Layout.BaseName is not null && nodes.TryGetValue(node.Layout.BaseName, out var parentNode) && parentNode.Games.Count > 0)
        {
            var forwarded = new HashSet<string>(StringComparer.Ordinal);
            foreach (var game in new[] { "" }.Concat(parentNode.Games))
            {
                foreach (var member in game.Length == 0 ? parentNode.Common : parentNode.Members.Where(m => m.Games.Contains(game)))
                {
                    var own = node.Members.FirstOrDefault(m => m.Name == member.Name);
                    if (own is null || own.Owner == member.Owner || Project(member, game, nodes) != member.Type) continue;
                    var common = game.Length > 0 && parentNode.Common.Any(m => m.Name == member.Name) &&
                        Project(member, "", nodes) == member.Type;
                    var contract = parentNode.Interface(common ? "" : game);
                    if (!forwarded.Add(contract + "." + member.Name)) continue;
                    var name = SyntaxOverlap.Escape(member.Name);
                    var access = $"(({parentNode.Layout.QualifiedName})this).{name}";
                    code.Open($"{member.Type} {contract}.{name}");
                    var required = !member.Type.EndsWith("?", StringComparison.Ordinal) && IsReferenceType(member.Type);
                    code.Line($"get => {access}{(required ? " ?? throw new MemberNullException(" + SymbolDisplay.FormatLiteral(member.Name, true) + ")" : "")};");
                    if (member.Writable) code.Line($"set => {access} = value;");
                    code.Close();
                }
            }
        }

        foreach (var game in new[] { "" }.Concat(node.Games))
        {
            foreach (var member in game.Length == 0 ? node.Common : node.Members.Where(m => m.Games.Contains(game)))
            {
                if (ExistingProperty(plan, node, game, member, nodes)) continue;
                var projected = Project(member, game, nodes);
                if (projected == member.Type) continue;
                var common = game.Length > 0 && node.Common.Any(m => m.Name == member.Name);
                if (common && projected == Project(member, "", nodes)) continue;
                var property = SyntaxOverlap.Escape(member.Name);
                var child = nodes[WireTypes.Map(member.Field!.StorageDeclaration.Type.Name)];
                var scalar = member.Field.StorageDeclaration.Type.ArrayDimensions == 0;
                var nullable = member.Type.EndsWith("?", StringComparison.Ordinal);
                code.Open($"{projected} {node.Interface(game)}.{property}");
                if (scalar)
                {
                    if (game.Length == 0) code.Line($"get => {property};");
                    else
                    {
                        code.Open("get");
                        code.Line($"var node = {property};");
                        if (!nullable) code.Line($"if (node is null) throw new MemberNullException({SymbolDisplay.FormatLiteral(member.Name, true)});");
                        code.Line($"if (node is not null) NodeBuilderValidation.Validate(node, GameVersion.{game});");
                        code.Line("return node;");
                        code.Close();
                    }
                    if (member.Writable)
                        code.Line($"set => {property} = value is null ? {(nullable ? "null" : "throw new ArgumentNullException(nameof(value))")} : value is {child.Layout.QualifiedName} node ? node : throw new ArgumentException(\"A GBX.NET node is required.\", nameof(value));");
                }
                else
                {
                    var element = GameNodeModel.Qualify(ReferenceModel.Element(member.Field), member.Owner, plan);
                    var view = child.Interface(game) + (element.EndsWith("?", StringComparison.Ordinal) ? "?" : "");
                    var missing = $"throw new MemberNullException({SymbolDisplay.FormatLiteral(member.Name, true)})";
                    var requiredElement = !element.EndsWith("?", StringComparison.Ordinal);
                    var projection = game.Length == 0 ? (requiredElement ? "node ?? " + missing : "node") :
                        $"{{ if (node is null) {(requiredElement ? missing + ";" : "return null;")} NodeBuilderValidation.Validate(node, GameVersion.{game}); return node; }}";
                    code.Line($"get => {(nullable ? property + " is null ? null : " : "")}new ScopedNodeList<{element}, {view}>(() => {property}, static node => {projection});");
                    if (member.Writable)
                        code.Line($"set => {property} = value is null ? {(nullable ? "null" : "throw new ArgumentNullException(nameof(value))")} : new NodeRefList<{element}>(value.Select(static item => {(requiredElement ? "" : "item is null ? null : ")}item is {child.Layout.QualifiedName} node ? node : throw new ArgumentException(\"A GBX.NET node is required.\", nameof(value))));");
                }
                code.Close();
            }
            foreach (var method in node.Methods.Where(m => game.Length == 0 ? node.Games.All(m.Games.Contains) : m.Games.Contains(game)))
            {
                if (ExistingMethod(plan, node, game, method)) continue;
                var returned = ProjectReturn(method, game, nodes);
                if (returned == method.ReturnType || game.Length > 0 && node.Games.All(method.Games.Contains) &&
                    returned == ProjectReturn(method, "", nodes)) continue;
                code.Line($"{returned} {node.Interface(game)}.{method.Declaration.Identifier.Text}({method.Parameters}) => {method.Declaration.Identifier.Text}({method.Arguments});");
            }
        }
        code.Close();
        return code.ToString();
    }

    private static string Builder(GameNodeModel node, GenerationPlan plan, Dictionary<string, GameNodeModel> nodes)
    {
        var code = Start(node.BuilderNamespace, plan);
        plan.Existing.TryGetValue(node.BuilderNamespace + "." + node.BuilderName, out var existing);
        EngineWriter.RequirePartial(existing);
        code.Open($"public abstract class {node.BuilderName}Base<TSelf> where TSelf : {node.BuilderName}Base<TSelf>");
        code.Line($"private protected readonly NodeBuilderState<{node.Layout.QualifiedName}> state;");
        code.Line($"private protected {node.BuilderName}Base() => state = new();");
        code.Line($"private protected {node.BuilderName}Base(NodeBuilderState<{node.Layout.QualifiedName}> state) => this.state = state;");
        foreach (var member in node.Members.Where(static m => m.Writable))
        {
            var mask = string.Join(" | ", member.Games.OrderBy(static g => g, StringComparer.Ordinal).Select(static g => "GameVersion." + g));
            code.Line($"private protected static void Set{member.Name}(NodeBuilderState<{node.Layout.QualifiedName}> state, {member.Type} value) => state.Set<{member.Type}>({SymbolDisplay.FormatLiteral(member.Name, true)}, value, {mask}, static value => {Copy(member, plan, "value")}, static (node, value) => node.{SyntaxOverlap.Escape(member.Name)} = value);");
            if (member.IsReference && member.Field?.StorageDeclaration.Type.ArrayDimensions == 0)
            {
                var element = GameNodeModel.Qualify(ReferenceModel.Element(member.Field), member.Owner, plan);
                code.Line($"private protected static void Set{member.Name}Reference(NodeBuilderState<{node.Layout.QualifiedName}> state, NodeRef<{element}> value) => state.Set<NodeRef<{element}>>({SymbolDisplay.FormatLiteral(member.Name, true)}, value, {mask}, static reference => {{ var copy = new NodeRef<{element}>(); copy.CopyFrom(reference); return copy; }}, static (node, reference) => node.References.{SyntaxOverlap.Escape(member.Name)}.CopyFrom(reference));");
            }
        }
        WriteMembers(code, node, "", null, plan, nodes);
        code.Close();
        code.Open($"public partial class {node.BuilderName} : {node.BuilderName}Base<{node.BuilderName}>");
        foreach (var game in node.Games.Where(g => !node.RecipeErrors.ContainsKey(g)))
        {
            if (!SyntaxOverlap.Method(existing, "For" + game)) code.Line($"public {game} For{game}() => new(state.Snapshot());");
            if (game == "MP4")
            {
                if (!SyntaxOverlap.Method(existing, "ForTM2")) code.Line("public MP4 ForTM2() => ForMP4();");
                if (!SyntaxOverlap.Method(existing, "ForSM")) code.Line("public MP4 ForSM() => ForMP4();");
            }
        }
        foreach (var game in node.Games.Where(g => !node.RecipeErrors.ContainsKey(g)))
        {
            plan.Existing.TryGetValue(node.BuilderNamespace + "." + node.BuilderName + "+" + game, out var stage);
            EngineWriter.RequirePartial(stage);
            code.Open($"public partial class {game} : {node.BuilderName}Base<{game}>");
            code.Line($"internal {game}(NodeBuilderState<{node.Layout.QualifiedName}> state) : base(state) {{ }}");
            WriteMembers(code, node, game, stage, plan, nodes);
            if (SyntaxOverlap.Has(stage, "Build") || SyntaxOverlap.Has(stage, "BuildInterface"))
                throw new InvalidOperationException("Build and BuildInterface are reserved for generated construction. Use the partial hooks.");
            code.Line($"public {node.Interface(game)} BuildInterface() => Build();");
            code.Open($"public {node.Layout.QualifiedName} Build()");
            var gameCtor = GameDefaultsWriter.Enabled(node.Layout.Scope, false) || node.Layout.Existing?.Constructors
                .Any(static c => c.ParameterList.Parameters.Count == 1 && SyntaxOverlap.Normalize(c.ParameterList.Parameters[0].Type?.ToString() ?? "") == "GameVersion") == true;
            code.Line($"var node = new {node.Layout.QualifiedName}({(gameCtor ? "GameVersion." + game : "")});");
            foreach (var candidate in node.Recipes[game])
            {
                var chunk = candidate.Chunk;
                var type = candidate.Owner.QualifiedName + "." + chunk.Name;
                var hasCtor = GameDefaultsWriter.Enabled(chunk.Scope, true) || chunk.Scope.Existing?.Constructors
                    .Any(static c => c.ParameterList.Parameters.Count == 1 && SyntaxOverlap.Normalize(c.ParameterList.Parameters[0].Type?.ToString() ?? "") == "GameVersion") == true;
                var variable = "chunk" + (chunk.IsHeader ? "Header" : "") + chunk.Id.ToString("X8");
                code.Line($"var {variable} = new {type}({(hasCtor ? "GameVersion." + game : "")});");
                if (candidate.HasVersion && !hasCtor) code.Line($"{variable}.Version = {candidate.Version(game)};");
                code.Line($"node.Chunks.Add({variable});");
            }
            code.Line($"state.Apply(node, GameVersion.{game});");
            code.Line("CustomizeNode(node);");
            foreach (var candidate in node.Recipes[game])
            {
                var chunk = candidate.Chunk;
                var chunkType = candidate.Owner.QualifiedName + "." + chunk.Name;
                var mismatch = candidate.HasVersion ? $" is not {{ Version: {candidate.Version(game)} }}" : " is null";
                code.Line($"if (node.GetChunk<{chunkType}>(){mismatch}) throw new InvalidOperationException(\"Required {game} chunk {chunk.Name} is missing or has an incompatible version.\");");
            }
            code.Line($"NodeBuilderValidation.Validate(node, GameVersion.{game});");
            foreach (var member in node.Members.Where(m => m.Games.Contains(game) && !m.Type.EndsWith("?", StringComparison.Ordinal)))
            {
                if (member.IsReference && member.Field?.StorageDeclaration.Type.ArrayDimensions == 0)
                    code.Line($"if (node.References.{SyntaxOverlap.Escape(member.Name)}.Kind == NodeRefKind.None) throw new MemberNullException({SymbolDisplay.FormatLiteral(member.Name, true)});");
                else if (IsReferenceType(member.Type))
                    code.Line($"if (node.{SyntaxOverlap.Escape(member.Name)} is null) throw new MemberNullException({SymbolDisplay.FormatLiteral(member.Name, true)});");
            }
            code.Line("ValidateNode(node);");
            code.Line("return node;");
            code.Close();
            code.Line($"partial void CustomizeNode({node.Layout.QualifiedName} node);");
            code.Line($"partial void ValidateNode({node.Layout.QualifiedName} node);");
            code.Close();
        }
        code.Close();
        return code.ToString();
    }

    private static bool IsReferenceType(string type) => type is "string" or "Ident" or "PackDesc" ||
        type.EndsWith("[]", StringComparison.Ordinal) || type.StartsWith("List<", StringComparison.Ordinal) ||
        type.StartsWith("NodeRefList<", StringComparison.Ordinal) || type.StartsWith("global::GBX.NET.Engines.", StringComparison.Ordinal) && !type.Contains(".E");

    private static void WriteMembers(CodeWriter code, GameNodeModel node, string game, ExistingType? existing,
        GenerationPlan plan, Dictionary<string, GameNodeModel> nodes)
    {
        var stage = game.Length == 0 ? "TSelf" : game;
        var self = game.Length == 0 ? "(TSelf)this" : "this";
        var members = (game.Length == 0 ? node.Common : node.Members.Where(m => m.Games.Contains(game))).Where(static m => m.Writable);
        foreach (var member in members)
        {
            var inherited = game.Length > 0 && node.Common.Any(m => m.Name == member.Name);
            if (inherited)
            {
                WriteScopedOverloads(code, node, game, member, nodes, "base.");
                continue;
            }
            var name = SyntaxOverlap.Escape(member.Name);
            var type = member.Type;
            if (!SyntaxOverlap.Has(existing, member.Name))
            {
                code.Open($"public {type} {name}");
                code.Line($"get => state.Get<{type}>({SymbolDisplay.FormatLiteral(member.Name, true)});");
                code.Line($"set => Set{member.Name}(state, value);");
                code.Close();
            }
            var method = "With" + member.Name;
            if (!SyntaxOverlap.Method(existing, method, type))
            {
                var arrayParameter = type.TrimEnd('?').EndsWith("[]", StringComparison.Ordinal) ? "params " : "";
                code.Open($"public {stage} {method}({arrayParameter}{type} value)");
                code.Line(SyntaxOverlap.Has(existing, member.Name) && existing?.Properties.Any(p => p.Identifier.ValueText == member.Name) != true
                    ? $"Set{member.Name}(state, value);" : $"{name} = value;");
                code.Line("return " + self + ";");
                code.Close();
            }

            if (member.IsReference && member.Field?.StorageDeclaration.Type.ArrayDimensions == 0)
            {
                var element = GameNodeModel.Qualify(ReferenceModel.Element(member.Field), member.Owner, plan);
                if (!SyntaxOverlap.Method(existing, method + "Reference", $"NodeRef<{element}>"))
                {
                    code.Open($"public {stage} {method}Reference(NodeRef<{element}> value)");
                    code.Line("if (value is null) throw new ArgumentNullException(nameof(value));");
                    code.Line($"Set{member.Name}Reference(state, value);");
                    code.Line("return " + self + ";");
                    code.Close();
                }
            }

            var elementType = CollectionElement(member.Type);
            if (elementType is not null && type.TrimEnd('?').EndsWith("[]", StringComparison.Ordinal) &&
                !SyntaxOverlap.Method(existing, method, $"IEnumerable<{elementType}>"))
            {
                code.Open($"public {stage} {method}(IEnumerable<{elementType}> values)");
                code.Line($"return {method}(values.ToArray());");
                code.Close();
            }
            if (elementType is not null && !type.TrimEnd('?').EndsWith("[]", StringComparison.Ordinal) &&
                !SyntaxOverlap.Method(existing, method, elementType + "[]"))
            {
                code.Open($"public {stage} {method}(params {elementType}[] values)");
                var conversion = member.Type.Contains("NodeRefList<") ? $"new NodeRefList<{elementType}>(values)" :
                    member.Type.Contains("List<") ? $"new List<{elementType}>(values)" : "values";
                code.Line($"return {method}({conversion});");
                code.Close();
                if (!SyntaxOverlap.Method(existing, method, $"IEnumerable<{elementType}>"))
                {
                    code.Open($"public {stage} {method}(IEnumerable<{elementType}> values)");
                    code.Line($"return {method}(values.ToArray());");
                    code.Close();
                }
            }
            WriteScopedOverloads(code, node, game, member, nodes, "");
        }
    }

    private static void WriteScopedOverloads(CodeWriter code, GameNodeModel node, string game, GameMember member,
        Dictionary<string, GameNodeModel> nodes, string prefix)
    {
        if (game.Length == 0 || Project(member, game, nodes) == member.Type) return;

        var method = "With" + member.Name;
        var child = nodes[WireTypes.Map(member.Field!.StorageDeclaration.Type.Name)];
        var childView = child.Interface(game);
        if (member.Field.StorageDeclaration.Type.ArrayDimensions == 0)
        {
            var nullable = member.Type.EndsWith("?", StringComparison.Ordinal);
            code.Open($"public {game} {method}({childView}{(nullable ? "?" : "")} value)");
            code.Line($"return {prefix}{method}({(nullable ? "value is null ? (" + member.Type + ")null : " : "")}value is {child.Layout.QualifiedName} node ? node : throw new ArgumentException(\"A GBX.NET node is required.\", nameof(value)));");
            code.Close();
        }
        else
        {
            var nullable = member.Field.Occurrences.Any(static d => d.Type.IsNullable);
            var convert = (nullable ? "value is null ? null : " : "") + $"value is {child.Layout.QualifiedName} node ? node : throw new ArgumentException(\"A GBX.NET node is required.\", nameof(values))";
            if (nullable) childView += "?";
            code.Open($"public {game} {method}(params {childView}[] values)");
            code.Line($"return {prefix}{method}(values.Select(static value => {convert}).ToArray());");
            code.Close();
            code.Open($"public {game} {method}(IEnumerable<{childView}> values)");
            code.Line($"return {method}(values.ToArray());");
            code.Close();
        }
    }

    private static string Copy(GameMember member, GenerationPlan plan, string value)
        => CopyType(member.Type, value, 0);

    private static string CopyType(string sourceType, string value, int depth)
    {
        var type = sourceType.TrimEnd('?');
        if (type.Contains("NodeRefList<") && !type.EndsWith("[]", StringComparison.Ordinal))
        {
            return $"{value} is null ? null! : NodeBuilderReferences.CopyList({value})";
        }
        if (type.EndsWith("[]", StringComparison.Ordinal))
        {
            var element = type.Substring(0, type.Length - 2);
            var item = "item" + depth;
            var copied = CopyType(element, item, depth + 1);
            return copied == item ? $"{value} is null ? null! : ({type}){value}.Clone()" :
                $"{value} is null ? null! : Array.ConvertAll({value}, static {item} => {copied})";
        }
        if (type.StartsWith("List<", StringComparison.Ordinal) || type.StartsWith("global::System.Collections.Generic.List<", StringComparison.Ordinal))
            return $"{value} is null ? null! : new {type}({value})";
        return value;
    }

    private static string? CollectionElement(string type)
    {
        type = type.TrimEnd('?');
        if (type.EndsWith("[]", StringComparison.Ordinal)) return type.Substring(0, type.Length - 2);
        if ((type.Contains("NodeRefList<") || type.StartsWith("List<", StringComparison.Ordinal) ||
            type.StartsWith("global::System.Collections.Generic.List<", StringComparison.Ordinal)) && type.EndsWith(">", StringComparison.Ordinal))
            return type.Substring(type.IndexOf('<') + 1, type.Length - type.IndexOf('<') - 2);
        return null;
    }

using ChunkL;
using ChunkL.Syntax;
using GBX.NET.Generators.Analysis;
using GBX.NET.Generators.Parsing;

namespace GBX.NET.Generators.Generation;

internal static class EngineWriter
{
    private static readonly DiagnosticDescriptor GenerationError = new(
        "GBXNETGEN200", "Cannot generate engine source", "Cannot generate {0}: {1}",
        "GBX.NET.Generators", DiagnosticSeverity.Error, true);

    public static void Generate(SourceProductionContext context, GenerationPlan plan)
    {
        foreach (var diagnostic in plan.Diagnostics)
        {
            context.ReportDiagnostic(diagnostic);
        }

        foreach (var layout in plan.Layouts.Values.OrderBy(static x => x.File.TypeKey, StringComparer.Ordinal))
        {
            context.CancellationToken.ThrowIfCancellationRequested();

            try
            {
                context.AddSource($"Engines/{layout.File.Engine}/{layout.Name}.g.cs", Write(layout, plan.Layouts, plan.Existing));
            }
            catch (Exception exception) when (exception is not OperationCanceledException)
            {
                context.ReportDiagnostic(Diagnostic(layout.File, exception));
            }
        }
    }

    internal static Diagnostic Diagnostic(ParsedChunkLFile file, Exception exception) =>
        Microsoft.CodeAnalysis.Diagnostic.Create(GenerationError,
            Location.Create(file.Path, default, default), file.Syntax.Header.ClassName, exception.Message);

    public static string Write(LayoutModel layout, IReadOnlyDictionary<string, LayoutModel> layouts,
        ImmutableDictionary<string, ExistingType> existingTypes)
    {
        RequirePartial(layout.Existing);

        var code = new CodeWriter();
        code.Line("// <auto-generated />");
        code.Line("#nullable enable");
        code.BlankLine();

        code.Line($"namespace {layout.File.Namespace};");
        code.BlankLine();

        Documentation(code, layout.File.Syntax.Header.TrailingComment?.Text);
        code.Line($"/// <remarks>ID: 0x{layout.Id:X8}</remarks>");

        if (!SyntaxOverlap.HasAttribute(layout.Existing, "Class"))
        {
            code.Line($"[Class(0x{layout.Id:X8})]");
        }

        var bases = new List<string>();
        if (layout.BaseName is not null) bases.Add(layout.BaseName);
        bases.Add("IClass");
        if (layout.SelfArchive is not null) bases.AddRange(ArchiveInterfaces(layout, layout.Scope));
        if (layout.Scope.HasVersion) bases.Add("IVersionable");

        var media = IsMedia(layout, layouts);
        if (media && layout.Scope.FindField("Keys") is not null)
        {
            bases.Add("CGameCtnMediaBlock.IHasKeys");
        }

        if (media && layout.Scope.FindField("Start") is not null
            && layout.Scope.FindField("End") is not null)
        {
            bases.Add("CGameCtnMediaBlock.IHasTwoKeys");
        }

        code.Open("public " + (layout.IsAbstract ? "abstract " : "") + "partial class " + layout.Name + (bases.Count == 0 ? "" : " : " + string.Join(", ", bases.Distinct())));

        if (!SyntaxOverlap.Has(layout.Existing, "Id"))
        {
            code.Line("[Hexadecimal]");
            code.Line($"public static {(layout.BaseName is null ? "" : "new ")}uint Id => 0x{layout.Id:X8};");
        }

        code.BlankLine();
        code.Line($"internal {(layout.BaseName is null ? "virtual" : "override")} uint GetId() => Id;");
        Properties(code, layout, layout.Scope, false, layouts, existingTypes);
        ReferenceView(code, layout, layout.Scope, layout.Name, false, layouts, existingTypes);

        if (layout.Name != "CMwNod" && !SyntaxOverlap.Method(layout.Existing, "DeepCloneFields", "CMwNod", "DeepCloneContext"))
        {
            code.BlankLine();
            code.Open("internal override void DeepCloneFields(CMwNod clone, DeepCloneContext context)");
            code.Line("base.DeepCloneFields(clone, context);");
            CloneFields(code, layout.Name, layout.Scope, false, layout, layouts, existingTypes);
            code.Close();
        }

        foreach (var property in layout.File.Syntax.Properties)
        {
            var partialProperty = SyntaxOverlap.PartialPropertyImplementation(layout.Existing, property.Name);
            if (SyntaxOverlap.Has(layout.Existing, property.Name) && partialProperty is null) continue;
            if (partialProperty is not null && layout.Scope.FindField(property.Name) is not null) continue;

            code.BlankLine();
            Documentation(code, property.TrailingComment?.Text);
            AppliedWithChunkAttributes(code, layout, property.Name, layouts);
            if (layout.Scope.FindField(property.Name) is { } field)
                GameDefaultAttributesWriter.Write(code, field);

            if (partialProperty is not null)
            {
                PartialProperty(code, partialProperty);
                continue;
            }

            code.Open("public " + WireTypes.CSharp(property.Type) + (property.Type.IsNullable && property.Type.ArrayDimensions == 0 ? "?" : "") + " " + SyntaxOverlap.Escape(property.Name));

            var writer = new SerializationWriter(code, layout, layout.Scope, layouts, existingTypes, SerializationMode.None, false);

            foreach (var accessor in property.Accessors)
            {
                if (accessor is GetterAccessor getter)
                    code.Line("get => " + (property.Type.Name == "int" ? writer.CountExpression(getter.Expression, WireTypes.CSharp(property.Type)) : writer.Expression(getter.Expression, WireTypes.CSharp(property.Type))) + ";");
                else if (accessor is SetterAccessor setter) { code.Open("set"); writer.Write(setter.Body); code.Close(); }
            }

            code.Close();
        }

        if (!GameDefaultsWriter.Write(code, layout, layout.Scope, layout.Name, layouts, existingTypes, false, layout.File.Syntax.Constructor) &&
            layout.Existing?.Constructors.Any(static x => !x.Modifiers.Any(SyntaxKind.StaticKeyword) && x.ParameterList.Parameters.Count == 0) != true &&
            layout.Existing?.PrimaryConstructors.Any() != true)
        {
            code.BlankLine();
            code.Open("public " + layout.Name + "()");

            if (layout.File.Syntax.Constructor is { } constructor)
                new SerializationWriter(code, layout, layout.Scope, layouts, existingTypes, SerializationMode.None, false).Write(constructor.Body);

            code.Close();
        }

        if (media && bases.Contains("CGameCtnMediaBlock.IHasKeys") && !SyntaxOverlap.Has(layout.Existing, "IHasKeys.Keys"))
        {
            code.BlankLine();
            code.Line("IEnumerable<IKey> CGameCtnMediaBlock.IHasKeys.Keys => Keys ?? []; ");
        }

        if (media && bases.Contains("CGameCtnMediaBlock.IHasTwoKeys"))
        {
            foreach (var name in new[] { "Start", "End" })
                if (!SyntaxOverlap.Has(layout.Existing, "IHasTwoKeys." + name))
                {
                    code.BlankLine();
                    code.Open($"TimeSingle CGameCtnMediaBlock.IHasTwoKeys.{name}");
                    code.Line($"get => {name}{(layout.Scope.Fields.First(x => x.Name == name).Declaration.Type.IsNullable ? ".GetValueOrDefault()" : "")};");
                    code.Line($"set => {name} = value;");
                    code.Close();
                }
        }

        if (layout.SelfArchive is not null)
        {
            code.BlankLine();
            ArchiveMethods(code, layout, layout.Scope, layouts, existingTypes,
                layout.BaseName is not null && layouts.TryGetValue(layout.BaseName, out var parent) && parent.SelfArchive is not null ? "override " : "virtual ");
        }

        foreach (var chunk in layout.Chunks.OrderBy(static x => x.IsHeader ? 0 : 1).ThenBy(static x => x.Id))
        {
            Chunk(code, layout, chunk, layouts, existingTypes);
        }

        foreach (var archive in layout.Archives)
        {
            code.BlankLine();
            RequirePartial(archive.Value.Existing);

            var inherited = LayoutModel.Attribute(archive.Value.Attributes, "inherits");
            var archiveBases = ArchiveInterfaces(layout, archive.Value).ToList();
            var inheritedArchive = inherited is not null && layout.Archives.ContainsKey(inherited);

            if (!string.IsNullOrEmpty(inherited)) archiveBases.Insert(0, inherited!);
            if (!inheritedArchive) archiveBases.Add("IDeepCloneable");

            code.Open($"public partial class {archive.Key} : {string.Join(", ", archiveBases)}");

            Properties(code, layout, archive.Value, false, layouts, existingTypes);
            ReferenceView(code, layout, archive.Value, archive.Key, false, layouts, existingTypes);
            GameDefaultsWriter.Write(code, layout, archive.Value, archive.Key, layouts, existingTypes, false);

            if (!inheritedArchive && archive.Value.Existing?.Methods.Any(static x => x.Identifier.ValueText == "DeepClone") != true)
            {
                code.BlankLine();
                code.Open("object IDeepCloneable.DeepClone(DeepCloneContext context)");
                code.Line($"var clone = ({archive.Key})MemberwiseClone();");
                code.Line("context.Register(this, clone);");
                code.Line("DeepCloneArchiveFields(clone, context);");
                code.Line("return clone;");
                code.Close();
            }

            code.BlankLine();
            code.Open($"internal {(inheritedArchive ? "override" : archive.Value.Existing?.Declarations.Any(static x => x.Modifiers.Any(SyntaxKind.SealedKeyword)) == true ? "" : "virtual")} void DeepCloneArchiveFields(object clone, DeepCloneContext context)");
            if (inheritedArchive) code.Line("base.DeepCloneArchiveFields(clone, context);");
            CloneFields(code, archive.Key, archive.Value, false, layout, layouts, existingTypes);
            code.Close();

            code.BlankLine();
            ArchiveMethods(code, layout, archive.Value, layouts, existingTypes,
                inheritedArchive ? "override " : "virtual ");

            code.Close();
        }

        foreach (var enumeration in layout.File.Syntax.Enums)
        {
            if (SyntaxOverlap.Has(layout.Existing, enumeration.Name)) continue;

            code.BlankLine();
            Documentation(code, enumeration.TrailingComment?.Text);

            code.Open("public enum " + enumeration.Name);

            foreach (var member in enumeration.Members)
            {
                Documentation(code, member.TrailingComment?.Text);
                code.Line(SyntaxOverlap.Escape(member.Name) + (member.ExplicitValue is null ? "" : " = " + member.ExplicitValue) + ",");
            }

            code.Close();
        }

        foreach (var flags in layout.File.Syntax.Flags)
        {
            if (SyntaxOverlap.Has(layout.Existing, flags.Name)) continue;

            code.BlankLine();
            code.Line("[Flags]");
            code.Open("public enum " + flags.Name + " : ulong");

            foreach (var member in flags.Members)
            {
                code.Line(SyntaxOverlap.Escape(member.Name) + " = " +
                    (member.Bits.IsSingleBit ? $"1UL << {member.Bits.Start}" : $"((1UL << {member.Bits.End - member.Bits.Start + 1}) - 1) << {member.Bits.Start}") + ",");
            }

            code.Close();
        }

        if (layout.Chunks.Any(static x => !x.IsHeader) && !SyntaxOverlap.Method(layout.Existing, "NewChunk", "uint") && layout.BaseName is not null)
        {
            code.BlankLine();
            code.Line("internal override IChunk? NewChunk(uint chunkId) => chunkId switch");
            code.Line("{");
            code.Indent++;

            foreach (var chunk in layout.Chunks.Where(static x => !x.IsHeader).OrderBy(static x => x.Id))
            {
                code.Line($"0x{chunk.Id:X8} => new {chunk.Name}(),");
            }

            code.Line("_ => base.NewChunk(chunkId),");
            code.Indent--;
            code.Line("};");
        }

        code.Close();

        return code.ToString();
    }

    internal static void RequirePartial(ExistingType? existing)
    {
        if (existing is not null && (!existing.IsPartial || existing.Declarations.Any(static x => x is not Microsoft.CodeAnalysis.CSharp.Syntax.ClassDeclarationSyntax)))
            throw new InvalidOperationException("Existing type must be a partial class: " + existing.Key);
    }

    private static string[] ArchiveInterfaces(LayoutModel layout, ScopeModel scope)
    {
        var contextual = LayoutModel.Has(scope.Attributes, "contextual") ? "<" + layout.Name + ">" : "";

        if (scope.Separate || contextual.Length > 0)
            return scope.HasVersion
                ? ["IReadable" + contextual, "IWritable" + contextual, "IVersionable"]
                : ["IReadable" + contextual, "IWritable" + contextual];

        return scope.HasVersion
            ? ["IReadableWritable", "IReadable", "IWritable", "IVersionable"]
            : ["IReadableWritable", "IReadable", "IWritable"];
    }

    private static void Properties(CodeWriter code, LayoutModel layout, ScopeModel scope, bool chunk,
        IReadOnlyDictionary<string, LayoutModel> layouts, IReadOnlyDictionary<string, ExistingType> existingTypes)
    {
        var gameDefaults = GameDefaultsWriter.Enabled(scope, chunk);
        foreach (var field in scope.Fields)
        {
            if (chunk && !field.IsUnknown && !field.IsVersion) continue;
            if (!chunk && field.Occurrences.Any(static x => LayoutModel.Has(x.Attributes, "inherited"))) continue;

            var property = SyntaxOverlap.Escape(field.Name);
            var backing = chunk ? property : SyntaxOverlap.Backing(field.Name);
            var nullable = WireTypes.Nullable(field) && !field.IsVersion;
            var storageDeclaration = field.StorageDeclaration;
            var type = field.IsVersion ? "int" : WireTypes.CSharp(storageDeclaration) + (nullable ? "?" : "");
            var defaultDeclaration = field.Occurrences.FirstOrDefault(static x => x.DefaultValue is not null);
            var initial = gameDefaults ? null : Default(layout, type, defaultDeclaration);
            if (gameDefaults && !nullable && !WireTypes.Value(storageDeclaration.Type.Name) && storageDeclaration.Type.CastTarget is null)
                initial = "default!";
            var partialProperty = SyntaxOverlap.PartialPropertyImplementation(scope.Existing, field.Name);
            var hasExisting = SyntaxOverlap.Has(scope.Existing, field.Name);
            var customProperty = !chunk && ReferenceEquals(scope, layout.Scope) &&
                layout.FindProperty(field.Name) is not null;

            if (ReferenceModel.IsNode(storageDeclaration, layout, layouts, existingTypes))
            {
                ReferenceProperty(code, layout, scope, field, chunk, partialProperty, layouts, existingTypes);
                continue;
            }

            if (!chunk)
                code.BlankLine();

            if (field.IsVersion)
            {
                if (partialProperty is not null)
                {
                    GameDefaultAttributesWriter.Write(code, field);
                    PartialProperty(code, partialProperty);
                }
                else if (!hasExisting)
                {
                    GameDefaultAttributesWriter.Write(code, field);
                    code.Line("public int Version { get; set; }" + (initial is null ? "" : " = " + initial + ";"));
                }
                continue;
            }

            if (chunk)
            {
                if (partialProperty is not null)
                {
                    GameDefaultAttributesWriter.Write(code, field);
                    PartialProperty(code, partialProperty);
                }
                else if (!hasExisting)
                {
                    GameDefaultAttributesWriter.Write(code, field);
                    code.Line("public " + type + " " + property + (initial is null ? "" : " = " + initial) + ";");
                }
            }
            else if (!hasExisting && customProperty)
            {
                if (!SyntaxOverlap.Has(scope.Existing, backing.TrimStart('@')))
                {
                    code.Line("private " + type + " " + backing + (initial is null ? "" : " = " + initial) + ";");
                }
            }
            else if (!hasExisting || partialProperty is not null)
            {
                if (partialProperty is null)
                {
                    var existingBacking = SyntaxOverlap.MemberType(scope.Existing, backing.TrimStart('@'));
                    if (existingBacking is not null)
                    {
                        type = existingBacking;
                    }
                    else
                    {
                        code.Line("private " + type + " " + backing + (initial is null ? "" : " = " + initial) + ";");
                    }
                }

                Documentation(code, field.Declaration.TrailingComment?.Text);
                if (ReferenceEquals(scope, layout.Scope))
                {
                    AppliedWithChunkAttributes(code, layout, field.Name, layouts);
                }

                GameDefaultAttributesWriter.Write(code, field);

                if (field.Occurrences.Any(static x => LayoutModel.Has(x.Attributes, "formatted")))
                    code.Line("[SupportsFormatting]");

                if (field.Occurrences.Any(static x => LayoutModel.Has(x.Attributes, "hex")))
                    code.Line("[Hexadecimal]");

                if (partialProperty is not null)
                {
                    PartialProperty(code, partialProperty);
                }
                else
                {
                    var privateSet = SyntaxOverlap.Option(scope.Existing, "PrivateSet") == "true" ? "private " : "";

                    code.Open($"public {type} {property}");
                    code.Line($"get => this.{backing};");
                    code.Line($"{privateSet}set => this.{backing} = value;");
                    code.Close();
                }
            }

        }
    }

    private static void ReferenceProperty(CodeWriter code, LayoutModel layout, ScopeModel scope, FieldModel field,
        bool chunk, PropertyDeclarationSyntax? partialProperty,
        IReadOnlyDictionary<string, LayoutModel> layouts, IReadOnlyDictionary<string, ExistingType> existingTypes)
    {
        var property = SyntaxOverlap.Escape(field.Name);
        var backing = chunk ? property : SyntaxOverlap.Backing(field.Name);
        var scalar = field.StorageDeclaration.Type.ArrayDimensions == 0;
        var element = ReferenceModel.Element(field);
        var type = scalar ? element + "?" : ReferenceModel.CollectionType(field) + "?";
        var customStorage = scalar ? SyntaxOverlap.MemberType(scope.Existing, backing.TrimStart('@')) : null;
        var convertedStorage = customStorage is not null && SyntaxOverlap.Normalize(customStorage) != SyntaxOverlap.Normalize(type);
        if (convertedStorage) type = customStorage!;
        var handle = ReferenceModel.Handle(field, chunk);
        code.BlankLine();

        if (scalar)
        {
            if (!SyntaxOverlap.Has(scope.Existing, handle))
                code.Line($"private NodeRef<{element}>? {handle};");
        }
        else if (!chunk && !SyntaxOverlap.Has(scope.Existing, backing.TrimStart('@')))
        {
            var initial = Default(layout, type, field.Declaration);
            if (initial == "NodeRefList<" + element + ">.Empty") initial = "new()";
            code.Line($"private {type} {backing}{(initial is null ? "" : " = " + initial)};");
        }

        if (!SyntaxOverlap.Has(scope.Existing, field.Name) || partialProperty is not null)
        {
            Documentation(code, field.Declaration.TrailingComment?.Text);
            if (!chunk && ReferenceEquals(scope, layout.Scope)) AppliedWithChunkAttributes(code, layout, field.Name, layouts);
            GameDefaultAttributesWriter.Write(code, field);
            if (partialProperty is not null) PartialProperty(code, partialProperty);
            else if (!scalar && chunk) code.Line($"public {type} {property};");
            else
            {
                code.Open($"public {type} {property}");
                code.Line($"get => {(convertedStorage ? handle + "?.Descriptor is null ? " + backing + " : (" + type + ")" + handle + ".Resolve()" : scalar ? handle + "?.Resolve()" : backing)};");
                if (convertedStorage) code.Line($"set {{ {backing} = value; NodeRef.SetEmbedded(ref {handle}, ({element}?)value); }}");
                else code.Line($"set => {(scalar ? "NodeRef.SetEmbedded(ref " + handle + ", value)" : backing + " = value")};");
                code.Close();
            }
        }

    }

    private static void ReferenceView(CodeWriter code, LayoutModel layout, ScopeModel scope, string className, bool chunk,
        IReadOnlyDictionary<string, LayoutModel> layouts, IReadOnlyDictionary<string, ExistingType> existingTypes)
    {
        var fields = scope.Fields.Where(field => (!chunk || field.IsUnknown) &&
            !field.Occurrences.Any(static x => LayoutModel.Has(x.Attributes, "inherited")) &&
            ReferenceModel.IsNode(field.StorageDeclaration, layout, layouts, existingTypes)).ToArray();
        if (scope.Fields.Any(static x => x.Name is "References" or "NodeRefView" or "EnumerateReferences"))
            throw new InvalidOperationException("References, NodeRefView, and EnumerateReferences are reserved for generated reference access.");
        if (fields.Length == 0 && !HasHandwrittenReferences(scope)) return;

        if (SyntaxOverlap.Has(scope.Existing, "References") || SyntaxOverlap.Has(scope.Existing, "NodeRefView"))
            throw new InvalidOperationException("References and NodeRefView are reserved for generated reference access.");
        var chunkBase = chunk ? LayoutModel.Attribute(scope.Attributes, "base") : null;
        var baseName = ReferenceEquals(scope, layout.Scope) ? layout.BaseName : chunkBase is not null ?
            "Chunk" + (LayoutModel.Hex(chunkBase) <= 0xFFF ? LayoutModel.Hex(chunkBase) | layout.Id : LayoutModel.Hex(chunkBase)).ToString("X8") :
            LayoutModel.Attribute(scope.Attributes, "inherits");
        var baseScope = baseName is not null && layouts.TryGetValue(baseName, out var parent) ? parent.Scope :
            baseName is not null && layout.Archives.TryGetValue(baseName, out var archive) ? archive :
            baseName is not null ? layout.Chunks.FirstOrDefault(x => x.Name == baseName)?.Scope : null;
        var inheritedMembers = baseScope is not null
            ? InheritedReferences(layout, baseName!, baseScope, chunk, layouts, existingTypes).ToArray()
            : [];
        var inherited = inheritedMembers.Length > 0;
        var members = ReferenceMembers(fields, scope, chunk).ToArray();
        var modifier = inherited ? "new " : "";
        code.BlankLine();
        code.Line($"public {modifier}NodeRefView References => new(this);");
        code.Open($"public {modifier}readonly struct NodeRefView");
        code.Line($"private readonly {className} owner;");
        code.Line($"internal NodeRefView({className} owner) => this.owner = owner;");
        foreach (var member in members)
        {
            var access = "owner." + member.Storage;
            var value = member.Dimensions switch
            {
                0 => $"NodeRef.GetOrCreate(ref {access})",
                1 => access + "?.References",
                _ => $"{access} is {{ }} rows ? Array.ConvertAll(rows, static row => row?.References) : null"
            };
            code.Line($"public {ReferenceViewType(member.Element, member.Dimensions)} {SyntaxOverlap.Escape(member.Name)} => {value};");
        }
        foreach (var member in inheritedMembers)
        {
            if (members.Any(x => x.Name == member.Name)) throw new InvalidOperationException("Ambiguous inherited reference: " + member.Name);
            var name = SyntaxOverlap.Escape(member.Name);
            code.Line($"public {ReferenceViewType(member.Element, member.Dimensions)} {name} => (({baseName})owner).References.{name};");
        }
        code.Close();

        if (SyntaxOverlap.Has(scope.Existing, "EnumerateReferences")) return;

        var overrides = ReferenceEquals(scope, layout.Scope) && layout.BaseName is not null || chunk || inherited;
        var sealedOwner = scope.Existing?.Declarations.Any(static x => x.Modifiers.Any(SyntaxKind.SealedKeyword)) == true;
        code.Open($"public {(overrides ? "override " : sealedOwner ? "" : "virtual ")}IEnumerable<KeyValuePair<string, NodeRef>> EnumerateReferences()");
        if (overrides) code.Line("foreach (var reference in base.EnumerateReferences()) yield return reference;");
        foreach (var member in members)
        {
            var name = SymbolDisplay.FormatLiteral(member.Name, true);
            if (member.Dimensions == 0)
                code.Line($"yield return new({name}, NodeRef.GetOrCreate(ref {member.Storage}));");
            else
            {
                var backing = member.Storage;
                code.Open($"if ({backing} is not null)");
                if (member.Dimensions == 1)
                    code.Line($"for (var i = 0; i < {backing}.Count; i++) yield return new({name} + \"[\" + i + \"]\", {backing}.Get(i));");
                else
                {
                    code.Open($"for (var i = 0; i < {backing}.Length; i++)");
                    code.Line($"if ({backing}[i] is null) continue;");
                    code.Line($"for (var j = 0; j < {backing}[i].Count; j++) yield return new({name} + \"[\" + i + \"][\" + j + \"]\", {backing}[i].Get(j));");
                    code.Close();
                }
                code.Close();
            }
        }
        code.Line("yield break;");
        code.Close();
    }

    private static bool HasHandwrittenReferences(ScopeModel scope) => scope.Existing?.Fields.Any(static field =>
        NodeReferenceType(field.Declaration.Type) is not null || NodeReferenceType(field.Declaration.Type, "NodeRefList") is not null) == true;

    private static GenericNameSyntax? NodeReferenceType(TypeSyntax type, string name = "NodeRef")
    {
        if (type is NullableTypeSyntax nullable) type = nullable.ElementType;
        var reference = type switch
        {
            GenericNameSyntax generic => generic,
            QualifiedNameSyntax qualified => qualified.Right as GenericNameSyntax,
            AliasQualifiedNameSyntax alias => alias.Name as GenericNameSyntax,
            _ => null
        };
        return reference?.Identifier.ValueText == name ? reference : null;
    }

    private static string ReferenceViewType(string element, int dimensions) => dimensions switch
    {
        0 => $"NodeRef<{element}>",
        1 => $"IReadOnlyList<NodeRef<{element}>>?",
        _ => $"IReadOnlyList<IReadOnlyList<NodeRef<{element}>>?>?"
    };

    private static IEnumerable<(string Name, string Element, string Storage, int Dimensions)> ReferenceMembers(
        IReadOnlyList<FieldModel> fields, ScopeModel scope, bool chunk)
    {
        foreach (var field in fields)
        {
            var dimensions = field.StorageDeclaration.Type.ArrayDimensions;
            var storage = dimensions == 0 ? ReferenceModel.Handle(field, chunk) :
                chunk ? SyntaxOverlap.Escape(field.Name) : SyntaxOverlap.Backing(field.Name);
            yield return (field.Name, ReferenceModel.Element(field), storage, dimensions);
        }

        if (scope.Existing is null) yield break;

        foreach (var declaration in scope.Existing.Fields)
        {
            var reference = NodeReferenceType(declaration.Declaration.Type);
            var list = NodeReferenceType(declaration.Declaration.Type, "NodeRefList");
            if (reference is null && list is null) continue;

            foreach (var variable in declaration.Declaration.Variables)
            {
                var storage = variable.Identifier.ValueText;
                if (reference is not null && !storage.EndsWith("Ref", StringComparison.Ordinal))
                    throw new InvalidOperationException("A handwritten NodeRef field must end in Ref: " + storage);
                var name = reference is null ? storage : storage.Substring(0, storage.Length - "Ref".Length);
                name = char.ToUpperInvariant(name[0]) + name.Substring(1);
                if (fields.Any(x => x.Name == name || (x.StorageDeclaration.Type.ArrayDimensions == 0
                    ? ReferenceModel.Handle(x, chunk)
                    : chunk ? SyntaxOverlap.Escape(x.Name) : SyntaxOverlap.Backing(x.Name)).TrimStart('@') == storage)) continue;
                yield return (name, (reference ?? list)!.TypeArgumentList.Arguments[0].ToString(), SyntaxOverlap.Escape(storage), reference is null ? 1 : 0);
            }
        }
    }

    private static IEnumerable<(string Name, string Element, string Storage, int Dimensions)> InheritedReferences(
        LayoutModel layout, string baseName, ScopeModel scope, bool chunk,
        IReadOnlyDictionary<string, LayoutModel> layouts, IReadOnlyDictionary<string, ExistingType> existingTypes)
    {
        var fields = scope.Fields.Where(x => (!chunk || x.IsUnknown) &&
            ReferenceModel.IsNode(x.StorageDeclaration, layout, layouts, existingTypes) &&
            !x.Occurrences.Any(static d => LayoutModel.Has(d.Attributes, "inherited"))).ToArray();
        foreach (var member in ReferenceMembers(fields, scope, chunk)) yield return member;
        if (layouts.TryGetValue(baseName, out var parent) && parent.BaseName is not null && layouts.TryGetValue(parent.BaseName, out var ancestor))
            foreach (var member in InheritedReferences(layout, ancestor.Name, ancestor.Scope, chunk, layouts, existingTypes)) yield return member;
        else if (LayoutModel.Attribute(scope.Attributes, "base") is { } chunkBase)
        {
            var chunkName = "Chunk" + (LayoutModel.Hex(chunkBase) <= 0xFFF ? LayoutModel.Hex(chunkBase) | layout.Id : LayoutModel.Hex(chunkBase)).ToString("X8");
            if (layout.Chunks.FirstOrDefault(x => x.Name == chunkName)?.Scope is { } ancestorScope)
                foreach (var member in InheritedReferences(layout, chunkName, ancestorScope, chunk, layouts, existingTypes)) yield return member;
        }
        else if (LayoutModel.Attribute(scope.Attributes, "inherits") is { } archiveBase && layout.Archives.TryGetValue(archiveBase, out var archiveScope))
        {
            foreach (var member in InheritedReferences(layout, archiveBase, archiveScope, chunk, layouts, existingTypes)) yield return member;
        }
    }

    private static void AppliedWithChunkAttributes(CodeWriter code, LayoutModel layout, string propertyName,
        IReadOnlyDictionary<string, LayoutModel> layouts)
    {
        var fields = new HashSet<string>(StringComparer.Ordinal) { propertyName };
        var property = layout.FindProperty(propertyName);
        if (property is not null)
        {
            foreach (var getter in property.Accessors.OfType<GetterAccessor>())
            {
                var expression = SyntaxFactory.ParseExpression(ChunkLParser.WriteExpression(getter.Expression));
                foreach (var identifier in expression.DescendantNodesAndSelf().OfType<IdentifierNameSyntax>())
                {
                    if (identifier.Parent is MemberAccessExpressionSyntax member && member.Name == identifier) continue;
                    if (layout.Scope.FindField(identifier.Identifier.ValueText) is not null)
                        fields.Add(identifier.Identifier.ValueText);
                }
            }
        }

        var applications = Applications().ToArray();
        var archiveRanges = layout.SelfArchive is null ? []
            : AppliedWithChunkRanges.GetArchive(layout.Scope, fields);
        if (applications.Length == 0 && archiveRanges.Count == 0) return;

        var groups = applications.GroupBy(static x => x.Chunk.IsHeader).Select(group =>
            string.Join(", ", group.Select(x => (x.Owner == layout ? "" : x.Owner.Name + ".") + $"0x{x.Chunk.Id & 0xFFF:X3}" +
                VersionText(x.Range))) +
            (group.Key ? " header" : " body") + (group.Count() == 1 ? " chunk" : " chunks"));
        if (archiveRanges.Count > 0)
            groups = groups.Append("archive" + string.Join(",", archiveRanges.Select(VersionText)));
        code.Line("/// <remarks>Applied with: " + string.Join(", ", groups) + "</remarks>");

        foreach (var application in applications)
        {
            var chunkType = (application.Owner == layout ? "" : application.Owner.QualifiedName + ".") + application.Chunk.Name;
            code.Line("[AppliedWithChunk<" + chunkType + ">" + VersionArguments(application.Range) + "]");
        }

        foreach (var range in archiveRanges)
        {
            code.Line("[AppliedWithArchive" + VersionArguments(range) + "]");
        }

        static string VersionText(AppliedWithChunkRanges.Range range)
            => range.End < int.MaxValue ? $" v{range.Start}-{range.End}" : range.Start > 0 ? $" v{range.Start}+" : "";

        static string VersionArguments(AppliedWithChunkRanges.Range range)
            => range.End < int.MaxValue ? $"({range.Start}, {range.End})" : range.Start > 0 ? $"({range.Start})" : "";

        IEnumerable<(LayoutModel Owner, ChunkModel Chunk, AppliedWithChunkRanges.Range Range)> Applications()
        {
            var descendants = layout.Descendants.Where(owner => fields.Any(name => InheritsField(owner, name)))
                .OrderBy(static x => x.File.TypeKey, StringComparer.Ordinal);
            foreach (var owner in new[] { layout }.Concat(descendants))
            {
                var names = fields.Where(name => owner == layout || InheritsField(owner, name)).ToArray();
                foreach (var chunk in owner.Chunks)
                {
                    foreach (var range in AppliedWithChunkRanges.Get(chunk, names, owner.Chunks, owner.Id))
                        yield return (owner, chunk, range);
                }
            }
        }

        bool InheritsField(LayoutModel owner, string name)
        {
            if (owner.Scope.FindField(name)?.Occurrences.Any(static x => LayoutModel.Has(x.Attributes, "inherited")) != true)
                return false;

            var visited = new HashSet<string>(StringComparer.Ordinal);
            while (owner != layout)
            {
                if (!visited.Add(owner.Name) || owner.FindProperty(name) is not null ||
                    owner.Existing?.Properties.Any(p => p.Identifier.ValueText == name && p.ExplicitInterfaceSpecifier is null) == true ||
                    owner.Scope.FindField(name) is { } field && !field.Occurrences.Any(static x => LayoutModel.Has(x.Attributes, "inherited")))
                    return false;

                if (owner.BaseName is null || !layouts.TryGetValue(owner.BaseName, out owner)) return false;
            }

            return true;
        }
    }

    private static void PartialProperty(CodeWriter code, PropertyDeclarationSyntax property)
    {
        var modifiers = string.Join(" ", property.Modifiers.Select(static x => x.Text));
        var accessors = string.Join(" ", property.AccessorList!.Accessors.Select(static x =>
            (x.Modifiers.Count == 0 ? "" : string.Join(" ", x.Modifiers.Select(static y => y.Text)) + " ") + x.Keyword.Text + ";"));

        code.Line($"{modifiers} {property.Type} {property.Identifier.Text} {{ {accessors} }}");
    }

    private static string? Default(LayoutModel layout, string type, FieldDeclaration? field)
        => Default(layout, type, field, field?.DefaultValue);

    internal static string? Default(LayoutModel layout, string type, FieldDeclaration? field, Expression? expression)
    {
        if (field is null || expression is null) return null;

        var value = ChunkLParser.WriteExpression(expression);
        if (LayoutModel.Has(field.Attributes, "time") && field.Type.ArrayDimensions == 0 && value is not ("null" or "default" or "empty"))
        {
            return "new " + WireTypes.Map(field.Type.Name, field.Attributes) + "(" + value + ")";
        }

        if (value != "empty") return value;

        type = type.TrimEnd('?');

        if (type.StartsWith("List<", StringComparison.Ordinal) || type.StartsWith("NodeRefList<", StringComparison.Ordinal)) return "new()";
        if (type.EndsWith("[]", StringComparison.Ordinal)) return "[]";
        if (type == "string") return "string.Empty";
        if (layout.Archives.ContainsKey(type)) return "new()";

        return type + ".Empty";
    }

    private static void WriteGameVersion(CodeWriter code, ChunkModel chunk)
    {
        var qualifiers = chunk.Declaration.VersionQualifiers;
        var games = Games(qualifiers);
        var versions = qualifiers.Where(static x => x.MaxVersion.HasValue).Select(static x => x.MaxVersion!.Value).Distinct().OrderBy(static x => x).ToArray();

        if (!chunk.Scope.HasVersion || versions.Length < 2)
        {
            code.Line("public override GameVersion GameVersion => " + games + ";");
            return;
        }

        code.Open("public override GameVersion GameVersion => Version switch");

        // A game supports every version up to its maximum. Games without a known maximum stay possible.
        foreach (var version in versions)
        {
            code.Line("<= " + version + " => " + Games(qualifiers.Where(x => (x.MaxVersion ?? version) >= version)) + ",");
        }

        code.Line("_ => " + games + ",");
        code.Close(";");

        static string Games(IEnumerable<VersionQualifier> qualifiers) => string.Join(" | ", qualifiers.Select(static x => "GameVersion." + x.Label));
    }

    private static void Chunk(CodeWriter code, LayoutModel layout, ChunkModel chunk, IReadOnlyDictionary<string, LayoutModel> layouts, IReadOnlyDictionary<string, ExistingType> existingTypes)
    {
        RequirePartial(chunk.Scope.Existing);
        code.BlankLine();
        var summary = $"{layout.Name} 0x{chunk.Id & 0xFFF:X3} {(LayoutModel.Has(chunk.Declaration.Attributes, "skippable") ? "skippable " : "")}chunk";
        if (!string.IsNullOrWhiteSpace(chunk.Declaration.TrailingComment?.Text))
            summary += $" ({chunk.Declaration.TrailingComment!.Text})";
        Documentation(code, summary);

        if (!SyntaxOverlap.HasAttribute(chunk.Scope.Existing, "Chunk"))
        {
            code.Line($"[Chunk(0x{chunk.Id:X8}{(chunk.Declaration.TrailingComment is { } comment ? ", " + SymbolDisplay.FormatLiteral(comment.Text, true) : "")})]");
        }

        if (chunk.Declaration.VersionQualifiers.Count > 0 && !SyntaxOverlap.HasAttribute(chunk.Scope.Existing, "ChunkGameVersion"))
        {
            var qualifiers = chunk.Declaration.VersionQualifiers;
            code.Line("[ChunkGameVersion(" + string.Join(" | ", qualifiers.Select(static x => "GameVersion." + x.Label)) +
                (qualifiers.Any(static x => x.MaxVersion.HasValue) ? ", " + string.Join(", ", qualifiers.Select(static x => x.MaxVersion ?? -1)) : "") + ")]");
        }

        var baseId = LayoutModel.Attribute(chunk.Declaration.Attributes, "base");
        var baseType = baseId is not null ? "Chunk" + (LayoutModel.Hex(baseId) <= 0xFFF ? LayoutModel.Hex(baseId) | layout.Id : LayoutModel.Hex(baseId)).ToString("X8") :
            (chunk.IsHeader ? "HeaderChunk" : LayoutModel.Has(chunk.Declaration.Attributes, "skippable") ? "SkippableChunk" : "Chunk") + "<" + layout.Name + ">";

        var interfaces = chunk.Scope.HasVersion ? ", IVersionable" : "";

        var selfContained = LayoutModel.Has(chunk.Declaration.Attributes, "self-contained");
        if (selfContained)
        {
            interfaces += ", ISelfContainedChunk<" + layout.Name + ">";
        }

        code.Open("public partial class " + chunk.Name + " : " + baseType + interfaces);

        if (!SyntaxOverlap.Has(chunk.Scope.Existing, "Id"))
        {
            code.Line($"public override uint Id => 0x{chunk.Id:X8};");
        }

        if (LayoutModel.Has(chunk.Declaration.Attributes, "ignore") && !SyntaxOverlap.Has(chunk.Scope.Existing, "Ignore"))
        {
            code.Line("public override bool Ignore => true;");
        }

        if (selfContained)
        {
            if (!SyntaxOverlap.Has(chunk.Scope.Existing, "Node"))
            {
                code.Line("public " + layout.Name + " Node { get; set; } = new();");
            }

            if (!SyntaxOverlap.Has(chunk.Scope.Existing, "ISelfContainedChunk.Node"))
            {
                code.Line("IClass ISelfContainedChunk.Node { get => Node; set => Node = (" + layout.Name + ")value; }");
            }
        }

        if (chunk.Declaration.VersionQualifiers.Count > 0 && !SyntaxOverlap.Has(chunk.Scope.Existing, "GameVersion"))
        {
            WriteGameVersion(code, chunk);
        }

        var demonstration = LayoutModel.Has(chunk.Declaration.Attributes, "demonstration");
        var omitMembers = LayoutModel.OmitsDemonstrationMembers(chunk.Declaration.Attributes);

        if (!omitMembers)
        {
            Properties(code, layout, chunk.Scope, true, layouts, existingTypes);
            ReferenceView(code, layout, chunk.Scope, chunk.Name, true, layouts, existingTypes);
            GameDefaultsWriter.Write(code, layout, chunk.Scope, chunk.Name, layouts, existingTypes, true);
        }

        if (!omitMembers && !SyntaxOverlap.Method(chunk.Scope.Existing, "DeepCloneFields", "Chunk", "DeepCloneContext"))
        {
            code.BlankLine();
            code.Open("internal override void DeepCloneFields(Chunk clone, DeepCloneContext context)");
            code.Line("base.DeepCloneFields(clone, context);");
            CloneFields(code, chunk.Name, chunk.Scope, true, layout, layouts, existingTypes);
            code.Close();
        }

        if (!demonstration && (chunk.Declaration.Body.Count > 0 || LayoutModel.Has(chunk.Declaration.Attributes, "empty")))
        {
            foreach (var mode in chunk.Scope.Separate ? new[] { SerializationMode.Read, SerializationMode.Write } : new[] { SerializationMode.ReadWrite })
            {
                var ioType = mode switch
                {
                    SerializationMode.Read => "GbxReader",
                    SerializationMode.Write => "GbxWriter",
                    _ => "GbxReaderWriter"
                };

                var io = mode switch
                {
                    SerializationMode.Read => "r",
                    SerializationMode.Write => "w",
                    _ => "rw"
                };

                if (SyntaxOverlap.Method(chunk.Scope.Existing, mode.ToString(), layout.Name, ioType))
                {
                    continue;
                }

                code.BlankLine();
                code.Open($"public override void {mode}({layout.Name} n, {ioType} {io})");

                new SerializationWriter(code, layout, chunk.Scope, layouts, existingTypes, mode, true).Write(chunk.Declaration.Body);

                code.Close();
            }
        }

        code.Close();
    }

    private static void CloneFields(CodeWriter code, string className, ScopeModel scope, bool chunk, LayoutModel layout,
        IReadOnlyDictionary<string, LayoutModel> layouts, IReadOnlyDictionary<string, ExistingType> existingTypes)
    {
        var copied = new HashSet<string>(StringComparer.Ordinal);

        foreach (var field in scope.Fields)
        {
            if (!chunk && field.Occurrences.Any(static x => LayoutModel.Has(x.Attributes, "inherited"))) continue;
            if (chunk && !field.IsUnknown && !field.IsVersion) continue;

            if (ReferenceModel.IsNode(field.StorageDeclaration, layout, layouts, existingTypes))
            {
                var scalar = field.StorageDeclaration.Type.ArrayDimensions == 0;
                var referenceName = scalar ? ReferenceModel.Handle(field, chunk) : chunk ? field.Name : SyntaxOverlap.Backing(field.Name);
                var referenceType = scalar ? "NodeRef<" + ReferenceModel.Element(field) + ">" : ReferenceModel.CollectionType(field);
                code.Line($"(({className})clone).{SyntaxOverlap.Escape(referenceName)} = {CloneExpression(referenceType, "this." + SyntaxOverlap.Escape(referenceName))};");
                var backingName = SyntaxOverlap.Backing(field.Name);
                var customStorage = scalar ? SyntaxOverlap.MemberType(scope.Existing, backingName.TrimStart('@')) : null;
                if (customStorage is not null && SyntaxOverlap.Normalize(customStorage.TrimEnd('?')) != ReferenceModel.Element(field))
                    code.Line($"(({className})clone).{backingName} = {CloneExpression(customStorage, "this." + backingName)};");
                copied.Add(field.Name);
                copied.Add(SyntaxOverlap.Backing(field.Name).TrimStart('@'));
                copied.Add(referenceName);
                continue;
            }
            if (!chunk && SyntaxOverlap.Has(scope.Existing, field.Name)) continue;

            var name = field.IsVersion ? "Version" : chunk ? field.Name : SyntaxOverlap.Backing(field.Name);
            if (!copied.Add(name)) continue;

            var type = field.IsVersion ? "int" : WireTypes.CSharp(field.StorageDeclaration);
            code.Line($"(({className})clone).{SyntaxOverlap.Escape(name)} = {CloneExpression(type, "this." + SyntaxOverlap.Escape(name))};");
        }

        if (scope.Existing is null) return;

        foreach (var field in scope.Existing.Fields)
        {
            if (field.Modifiers.Any(SyntaxKind.StaticKeyword) ||
                field.Modifiers.Any(SyntaxKind.ConstKeyword) ||
                field.Modifiers.Any(SyntaxKind.ReadOnlyKeyword)) continue;

            foreach (var variable in field.Declaration.Variables)
            {
                var name = variable.Identifier.ValueText;
                if (!copied.Add(name)) continue;

                var escaped = SyntaxOverlap.Escape(name);
                code.Line($"(({className})clone).{escaped} = {CloneExpression(field.Declaration.Type.ToString(), "this." + escaped)};");
            }
        }

        foreach (var property in scope.Existing.Properties)
        {
            if (property.ExplicitInterfaceSpecifier is not null ||
                property.Modifiers.Any(SyntaxKind.StaticKeyword) ||
                property.AccessorList?.Accessors.Any(x => x.IsKind(SyntaxKind.SetAccessorDeclaration)) != true ||
                property.AccessorList.Accessors.Any(x => x.Body is not null || x.ExpressionBody is not null)) continue;

            var name = property.Identifier.ValueText;
            if (!copied.Add(name)) continue;

            var escaped = SyntaxOverlap.Escape(name);
            code.Line($"(({className})clone).{escaped} = {CloneExpression(property.Type.ToString(), "this." + escaped)};");
        }
    }

    private static string CloneExpression(string type, string value)
    {
        var name = type.TrimEnd('?').Split('<')[0].Split('.').Last();

        if (type.TrimEnd('?').EndsWith("[]", StringComparison.Ordinal)) return CloneArrayExpression(type.TrimEnd('?'), value, 0);
        if (name is "List" or "IList" or "IReadOnlyList" or "ICollection" or "IReadOnlyCollection" or "IEnumerable")
            return $"context.CloneList({value})!";
        if (name is "Dictionary" or "IDictionary" or "IReadOnlyDictionary")
            return $"context.CloneDictionary({value})!";
        if (name == "SortedDictionary") return $"context.CloneSortedDictionary({value})!";
        if (name is "HashSet" or "ISet") return $"context.CloneHashSet({value})!";

        return $"context.Clone({value})!";
    }

    private static string CloneArrayExpression(string type, string value, int depth)
    {
        var element = type.Substring(0, type.Length - 2).TrimEnd('?');
        if (!element.EndsWith("[]", StringComparison.Ordinal)) return $"context.CloneArray({value})!";
        var parameter = "row" + depth;
        return $"context.CloneArray({value}, {parameter} => {CloneArrayExpression(element, parameter, depth + 1)})!";
    }

    private static void ArchiveMethods(CodeWriter code, LayoutModel layout, ScopeModel scope, IReadOnlyDictionary<string, LayoutModel> layouts, IReadOnlyDictionary<string, ExistingType> existingTypes, string modifier)
    {
        if (scope.Existing?.Declarations.Any(static x => x.Modifiers.Any(SyntaxKind.SealedKeyword)) == true)
        {
            modifier = "";
        }

        var contextual = LayoutModel.Has(scope.Attributes, "contextual");

        foreach (var mode in scope.Separate || contextual ? new[] { SerializationMode.Read, SerializationMode.Write } : new[] { SerializationMode.ReadWrite })
        {
            var ioType = mode switch
            {
                SerializationMode.Read => "GbxReader",
                SerializationMode.Write => "GbxWriter",
                _ => "GbxReaderWriter"
            };

            var io = mode switch
            {
                SerializationMode.Read => "r",
                SerializationMode.Write => "w",
                _ => "rw"
            };

            var parameterTypes = contextual ? new[] { ioType, layout.Name, "int" } : new[] { ioType, "int" };

            if (SyntaxOverlap.Method(scope.Existing, mode.ToString(), parameterTypes))
            {
                continue;
            }

            code.BlankLine();
            code.Open($"public {modifier}void {mode}({ioType} {io}, {(contextual ? layout.Name + " n, " : "")}int v = 0)");

            new SerializationWriter(code, layout, scope, layouts, existingTypes, mode, false).Write(scope.Body);

            code.Close();
        }

        // Separate chunk methods also need to call archives implemented with a single
        // ReadWrite method. Adapt those interfaces without duplicating serialization.
        if (!scope.Separate && !contextual)
        {
            foreach (var mode in new[] { SerializationMode.Read, SerializationMode.Write })
            {
                var ioType = mode == SerializationMode.Read ? "GbxReader" : "GbxWriter";
                var io = mode == SerializationMode.Read ? "r" : "w";

                if (SyntaxOverlap.Method(scope.Existing, mode.ToString(), ioType, "int"))
                {
                    continue;
                }

                code.BlankLine();
                code.Open($"public {modifier}void {mode}({ioType} {io}, int v = 0)");
                code.Line($"using var rw = new GbxReaderWriter({io});");
                code.Line("ReadWrite(rw, v);");
                code.Close();
            }
        }
    }

    private static bool IsMedia(LayoutModel layout, IReadOnlyDictionary<string, LayoutModel> layouts)
    {
        var seen = new HashSet<string>(StringComparer.Ordinal);

        while (layout.BaseName is not null && seen.Add(layout.Name))
        {
            if (layout.BaseName == "CGameCtnMediaBlock")
            {
                return true;
            }

            if (!layouts.TryGetValue(layout.BaseName, out layout!))
            {
                return false;
            }
        }

        return false;
    }

    private static void Documentation(CodeWriter code, string? text)
    {
        if (string.IsNullOrWhiteSpace(text))
        {
            return;
        }

        code.Line("/// <summary>");

        foreach (var line in text!.Split('\n'))
        {
            code.Line("/// " + line.Trim().Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;"));
        }

        code.Line("/// </summary>");
    }
